export function createUserI18n(): UserI18n {
  return createCatalogI18n(catalog, preferredLocale())
}

export function useUserI18n(): UserI18n {
  return useCatalogI18n(userI18nKey)
}

export function setUserLocale(i18n: UserI18n, value: unknown): boolean {
  if (!i18n.setLocale(value)) return false
  writeLocaleCookie(i18n.locale.value)
  return true
}
