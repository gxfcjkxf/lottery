export type PlatformI18n = CatalogI18n & { setLocale(value: unknown): boolean }
export const platformI18nKey = createI18nKey<PlatformI18n>('platform-i18n')

export function createPlatformI18n(): PlatformI18n {
  const base = createCatalogI18n(catalog, preferredLocale())
  return {
    ...base,
    setLocale(value: unknown) {
      if (!base.setLocale(value)) return false
      writeLocaleCookie(base.locale.value)
      return true
    },
  }
}

export function usePlatformI18n(): PlatformI18n {
  return useCatalogI18n(platformI18nKey)
}
