import {expect,test} from '@playwright/test'
for(const locale of ['zh-CN','en'] as const)test(`fixed management entry login and session (${locale})`,async({page},info)=>{
 const zh=locale==='zh-CN',errors:string[]=[]
 page.on('pageerror',e=>errors.push(e.message))
 await page.context().addCookies([{name:'lottery-locale',value:locale,url:info.project.use.baseURL!}])
 await page.goto('/')
 await expect(page.locator('.login-entry__card')).toBeVisible()
 await expect(page.getByRole('button',{name:zh?'登录':'Sign in',exact:true})).toBeEnabled()
 expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth+1)).toBe(true)
 await page.screenshot({path:info.outputPath('fixed-entry-login.png'),fullPage:true})
 const suffix=info.project.name.replaceAll('-','_')+'_'+(zh?'zh':'en')
 await page.getByLabel(zh?'账号':'Account',{exact:true}).fill('review_'+suffix)
 await page.getByLabel(zh?'密码':'Password',{exact:true}).fill('agent123')
 await page.getByRole('button',{name:zh?'登录':'Sign in',exact:true}).click()
 await expect(page.locator('.management-console')).toBeVisible()
 await expect(page.locator('.auth-brand-name')).toHaveCount(0)
 await page.reload()
 await expect(page.locator('.management-console')).toBeVisible()
 expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth+1)).toBe(true)
 await page.screenshot({path:info.outputPath('fixed-entry-session.png'),fullPage:true})
 await page.locator('.account-trigger').click()
 await page.getByRole('menuitem',{name:zh?'退出登录':'Sign out',exact:true}).click()
 await expect(page.locator('.login-entry__card')).toBeVisible()
 expect(errors).toEqual([])
})
