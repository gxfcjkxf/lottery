import {expect,test} from '@playwright/test'
for(const locale of ['zh-CN','en'] as const)test(`independent agent can add members and direct agents (${locale})`,async({page},info)=>{
 const suffix=info.project.name.replaceAll('-','_')+'_'+(locale==='zh-CN'?'zh':'en')
 const zh=locale==='zh-CN',errors:string[]=[];page.on('pageerror',e=>errors.push(e.message))
 await page.context().addCookies([{name:'lottery-locale',value:locale,url:info.project.use.baseURL!}])
 await page.goto('/?brand=aurora')
 const login=async(account:string,password:string)=>{
  await page.getByLabel(zh?'账号':'Account',{exact:true}).fill(account)
  await page.getByLabel(zh?'密码':'Password',{exact:true}).fill(password)
  await page.getByRole('button',{name:zh?'登录':'Sign in',exact:true}).click()
  await expect(page.locator('.management-console')).toBeVisible()
  await expect(page.locator('.account-trigger')).toContainText(account[0].toUpperCase())
 }
 const navigate=async(id:string)=>{
  const nav=page.locator(page.viewportSize()!.width<=700?'.mobile-nav':'.side-nav')
  await nav.locator(`a[href="#/${id}"]`).click()
  await expect(page).toHaveURL(new RegExp('#/'+id+'$'))
 }
 const logout=async()=>{
  await page.locator('.account-trigger').click()
  await page.getByRole('menuitem',{name:zh?'退出登录':'Sign out',exact:true}).click()
  await expect(page.locator('.login-entry')).toBeVisible()
 }
 await login('review_'+suffix,'agent123')
 await expect(page.getByRole('alert')).toHaveCount(0)
 const member='member_'+suffix,child='child_'+suffix,descendant='desc_'+suffix
 await page.getByRole('button',{name:zh?'添加会员':'Add member',exact:true}).click()
 const editor=page.getByRole('dialog')
 await editor.getByLabel(zh?'账号':'Account',{exact:true}).fill(member)
 await editor.getByLabel(zh?'密码':'Password',{exact:true}).fill('member123')
 await editor.getByLabel(zh?'昵称':'Display name',{exact:true}).fill(zh?'专属测试会员':'Test member')
 await editor.getByRole('button',{name:zh?'保存':'Save',exact:true}).click();await expect(editor).toHaveCount(0)
 const directory=page.locator('.member-directory'),summary=directory.locator('.facts')
 const row=(account:string)=>directory.locator('tbody tr').filter({has:page.locator('td', {hasText:new RegExp('^'+account+'$')})})
 await expect(row(member)).toHaveCount(1)
 await expect(summary.locator('dd').first()).toHaveText('1')
 await expect(row(descendant)).toHaveCount(0)
 await directory.getByRole('button',{name:zh?'全代理线':'Full agent line',exact:true}).click()
 await expect(row(descendant)).toHaveCount(1)
 await expect(summary.locator('dd').first()).toHaveText('2')
 await row(descendant).getByRole('button',{name:zh?'查看注单':'View bets',exact:true}).click()
 await expect(page.locator('.member-bets .section-head strong')).toHaveText(descendant)
 await expect(page.locator('.member-bets .facts')).toContainText(zh?'输赢':'Net winnings')
 await page.reload()
 await expect(page.locator('.member-bets .section-head strong')).toHaveText(descendant)
 await expect(page.getByRole('alert')).toHaveCount(0)
 await navigate('members')
 await expect(row(descendant)).toHaveCount(0)
 await row(member).getByRole('button',{name:zh?'查看注单':'View bets',exact:true}).click()
 await expect(page.locator('.member-bets .section-head strong')).toHaveText(member)
 await expect(page.locator('.member-bets .facts dd')).toHaveText(['0','0','0'])
 await navigate('commission')
 await expect(page.locator('.commission-page .facts dd')).toHaveText(['0','0','0'])
 await expect(page.locator('.commission-page .empty-state')).toBeVisible()
 await navigate('children')
 await page.getByRole('button',{name:zh?'添加下级代理':'Add subagent',exact:true}).click()
 await editor.getByLabel(zh?'账号':'Account',{exact:true}).fill(child)
 await editor.getByLabel(zh?'密码':'Password',{exact:true}).fill('agent123')
 await editor.getByLabel(zh?'占成比例':'Profit share ratio',{exact:true}).fill('0')
 await editor.getByRole('button',{name:zh?'保存':'Save',exact:true}).click();await expect(editor).toHaveCount(0)
 await expect(page.locator('.children-directory')).toContainText(child)
 const preset=page.viewportSize()!
 for(const width of info.project.name==='desktop'?[320,640,900,1440]:[preset.width]){
  if(info.project.name==='desktop')await page.setViewportSize({width,height:preset.height})
  const sizes=await page.evaluate(()=>({width:innerWidth,scroll:document.documentElement.scrollWidth}))
  expect(sizes.scroll).toBeLessThanOrEqual(sizes.width+1)
 }
 await page.screenshot({path:info.outputPath(`portal-${locale}.png`)})
 await logout()
 await login(child,'agent123')
 await navigate('children')
 await expect(page.getByRole('button',{name:zh?'添加下级代理':'Add subagent',exact:true})).toHaveCount(0)
 await page.locator('.account-trigger').click()
 await page.getByRole('menuitem',{name:zh?'修改密码':'Change password',exact:true}).click()
 const passwordDialog=page.getByRole('dialog',{name:zh?'修改密码':'Change password',exact:true})
 await passwordDialog.getByLabel(zh?'当前密码':'Current password',{exact:true}).fill('agent123')
 await passwordDialog.getByLabel(zh?'新密码':'New password',{exact:true}).fill('changed456')
 await passwordDialog.getByLabel(zh?'确认新密码':'Confirm new password',{exact:true}).fill('changed456')
 await passwordDialog.getByRole('button',{name:zh?'保存密码':'Save password',exact:true}).click()
 await expect(page.locator('.login-entry')).toBeVisible()
 await expect(page.getByRole('status').filter({hasText:zh?'密码已修改':'Password changed'})).toBeVisible()
 await login(child,'changed456')
 await navigate('children')
 await expect(page.getByRole('button',{name:zh?'添加下级代理':'Add subagent',exact:true})).toHaveCount(0)
 await logout()
 expect(errors).toEqual([])
})
